function languageTag(locale: Locale): string {
  return locale === 'vi' ? 'vi-VN' : 'en-US';
}

export function formatVnd(locale: Locale, amountVnd: number): string {
  return new Intl.NumberFormat(languageTag(locale), {
    style: 'currency',
    currency: 'VND',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amountVnd);
}

export function formatDateTime(locale: Locale, instant: string | Date): string {
  return new Intl.DateTimeFormat(languageTag(locale), {
    timeZone: 'Asia/Ho_Chi_Minh',
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(typeof instant === 'string' ? new Date(instant) : instant);
}

export function formatTime(locale: Locale, instant: string | Date): string {
  return new Intl.DateTimeFormat(languageTag(locale), {
    timeZone: 'Asia/Ho_Chi_Minh',
    hour: '2-digit',
    minute: '2-digit',
  }).format(typeof instant === 'string' ? new Date(instant) : instant);
}
