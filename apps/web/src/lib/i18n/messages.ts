function isPaymentStatus(value: string): value is keyof typeof paymentStatusKeys {
  return value in paymentStatusKeys;
}

export function translatePaymentStatus(locale: Locale, status: string | null | undefined): string {
  return translate(
    locale,
    status !== undefined && status !== null && isPaymentStatus(status)
      ? paymentStatusKeys[status]
      : 'payment.status.UNKNOWN',
  );
}

